// 민감정보(건강 · 성생활 · 종교 · 정치 · 성적 지향 · 가족사)로 보이는 표현.
// AI가 제안한 성향에서 걸러 낸다 (설계 원칙: 민감정보 추론 · 저장 금지).
// 프롬프트에서도 금지하지만, 모델이 어겨도 저장 제안까지 가지 않게 한 번 더 막는다.
// 소통 방식("불안할 때 질문이 많아지는 편")은 남기고, 진단 · 신앙 · 성향 같은 사실만 잡는다.
const PATTERNS = [
  /우울증|공황|불안장애|정신과|상담을? 받|약을? 먹|복용|질환|질병|투병|병원에? 다니|임신|생리/,
  /성관계|섹스|성생활|스킨십|야한/,
  /종교|교회|성당|기독|천주교|불교|신자|신앙|예배|기도/,
  // "보수적인 편"처럼 성격을 말하는 표현은 남기고, 정치 성향 · 정당만 잡는다
  /정치|(?:진보|보수) ?(?:성향|정당|정권|언론|지지)|민주당|국민의힘|투표/,
  /동성애|성소수자|성적 지향|성 정체성/,
  /가족사|이혼|돌아가신|사별/,
];

export function isSensitiveText(text: string): boolean {
  return PATTERNS.some((p) => p.test(text));
}
