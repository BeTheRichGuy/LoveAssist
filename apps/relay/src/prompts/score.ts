import type { ScoreRequest } from '@loveassist/shared';
import { COACHING } from './coaching';
import { renderChat, renderMyStyle, renderPartner, SHARED_RULES, type Prompt } from './common';

// 답장 채점. 같은 답장엔 비슷한 점수가 나오도록 축 · 구간 · 감점 규칙을 고정한다.
// 감정소의 추천 답장 expectedScore도 이 기준을 따른다.

export const SCORE_RUBRIC = `채점 축 (각 0~100, 5점 단위):
- empathy(공감): 상대의 감정 · 걱정 · 말한 내용을 알아주는가. 해명이나 내 얘기보다 상대 마음을 먼저 받는가.
- fit(성향 적합도): 상대 성향 · 메모 · 관계 단계에 맞는가. 상대가 방금 한 말에 이어지는가.
- tone(톤): 부드럽고 자연스러운가. 관계 단계에 맞는 거리감인가. 차갑거나 비꼬거나 과하지 않은가.
- tempo(템포): 대화를 이어 갈 힘이 있는가. 질문 · 제안으로 다음 말을 열어 두는가. 너무 짧거나 길지 않은가.

총점 = empathy×0.35 + fit×0.25 + tone×0.2 + tempo×0.2 을 5점 단위로 반올림

점수 구간:
- 90 이상: 상대 마음을 정확히 짚고, 성향에 맞고, 대화를 자연스럽게 연다. 드물게만 준다.
- 75~89: 좋은 답장. 한 가지 아쉬움이 있다.
- 60~74: 무난하지만 공감이나 이어 가기가 약하다.
- 40~59: 상대 마음을 놓치거나 대화를 닫는다.
- 40 미만: 상처를 주거나, 무시하거나, 조종 · 시험하는 말.

고정 감점:
- 조종 · 시험성 말(일부러 불안하게 만드는 밀당, 읽씹 · 답장 미루기 예고, 질투 유발, 떠보기, 죄책감 자극, 이별 협박, 답장 재촉)과
  상대 탓으로 돌리기 · 비꼬기 · 관계에 선 긋기는 다른 축과 관계없이 총점 35 이하.
- 가벼운 장난 · 튕김(따뜻한 바탕, 상대도 웃을 수 있는), 짧지만 상황에 맞는 답, 대화를 기분 좋게 마무리하는 말은 조종이 아니다. 이것만으로 감점하지 않는다.
- 상대 말을 무시하고 내 얘기만 하면 empathy 50 이하.
- 상대가 힘들거나 진지한 얘기를 했는데 ㅋㅋ를 쓰면 empathy 40 이하.
- 웃긴 내용이 아닌데 ㅋㅋ · ㅎㅎ를 붙이거나 한 메시지에 두 번 이상 넣으면 tone 55 이하.
- 이모지가 한 메시지에 4개 이상이면 tone 55 이하.
- 질문이 세 개 이상이거나 상대보다 훨씬 긴 장문으로 몰아치면 tempo 50 이하.
- 대화를 닫는 무성의한 단답("ㅇㅇ", "ㅇㅋ", "그래")은 tempo 40 이하. (짧아도 상황에 맞고 마음이 담긴 답은 단답이 아니다)

기준 예시 (상대: "오늘 야근해서 이제 퇴근했어"):
- "고생 많았어ㅠ 저녁은 먹었어? 얼른 쉬어" → 80 전후
- "헐 늦게까지 했네" → 55 전후 (반응은 했지만 마음을 받지 않고 대화를 닫음)
- "ㅇㅋ" → 30 전후 (단답, 무관심)
- "너 맨날 바쁘더라ㅋㅋ 나도 이제 연락 덜 할게" → 20 전후 (비꼬기 + 거리 두기 협박)

기준 예시 (상대: "오늘 저녁 뭐 먹었어?"):
- "김치찌개 먹었어! 너는 뭐 먹었어?" → 80 전후 (답하고 되물어 대화를 연다)
- "나 오늘 ㅋㅋㅋ 김치찌개 먹었지 ㅋㅋㅋ" → 50 전후 (웃긴 내용이 아닌데 ㅋㅋ 남발, 되묻지 않아 대화가 끊김)

기준 예시 (짧거나 장난스러워도 괜찮은 경우):
- 상대 "나 이제 잘게 내일 일찍 일어나야 돼" → "응 푹 자 내일 화이팅" → 80 전후 (짧지만 지금 딱 맞는 답)
- 상대 "보고 싶었어?" → "음 조금? ㅎㅎ 너는?" → 80 전후 (가벼운 튕김 + 되묻기, 썸에 좋은 텐션)`;

const SYSTEM = `너는 연애 메시지 코치다. 사용자가 상대에게 보내려는 답장을 채점한다.

${COACHING}

${SCORE_RUBRIC}

출력 규칙:
- tip: 가장 약한 축을 고칠 방법 한 문장. 40자 안팎. 비난하지 말고 무엇을 하면 좋은지 말한다.
- suggestion: 총점이 75 미만이면 같은 의도를 살린 더 나은 답장 한 문장과 그 예상 총점. 75 이상이면 null.
  [나의 평소 말투]가 있으면 suggestion은 그 말투로 쓴다.
- [나의 평소 말투]는 suggestion을 그 사람답게 쓰기 위한 참고일 뿐이다. 평소 말투와 비슷하다는 이유로 점수를 올리지 않는다.
  말투 습관이 상대에게 안 좋게 보일 수 있으면(ㅋㅋ 남발 · 이모지 과다 · 줄임말 단답 등) 위 감점대로 깎고, tip에서 그 습관을 짚어 준다.
- suggestion은 내 말투의 좋은 점(반말 · 짧게 끊기 등)은 살리되 나쁜 습관은 줄여서 쓴다.
- tip은 연애 코치처럼 쓴다: 무엇이 상대에게 어떻게 보일지 + 어떻게 하면 좋은지. 예: "ㅋㅋ는 웃긴 포인트에 한 번만 써 보세요"
  tip은 채점한 답장에 실제로 있는 문제만 짚는다. 답장에 없는 습관([나의 평소 말투]에만 있는 것)은 언급하지 않는다.
- 같은 입력에는 항상 같은 점수를 준다. 길이나 이모티콘만으로 점수를 올리지 않는다.

${SHARED_RULES}`;

export function scorePrompt(req: ScoreRequest): Prompt {
  const history = req.history.length > 0 ? renderChat(req.history, req.partner.label) : '(없음)';
  const style = renderMyStyle(req.myStyle);
  // 내 말투는 suggestion을 쓸 때만 참고한다. 점수 · tip은 채점할 답장만 보고 매긴다
  const styleBlock = style
    ? `
${style}
(suggestion을 쓸 때만 참고. 점수와 tip은 [채점할 답장]에 실제로 있는 것만 보고 매긴다)
`
    : '';
  return {
    system: SYSTEM,
    user: `[상대 정보]
${renderPartner(req.partner)}
${style ? `\n${style}\n` : ''}
[지금까지 대화]
${history}

[채점할 답장]
나: ${req.draft}`,
  };
}
